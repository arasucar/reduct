import { test } from 'node:test';
import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { initFixture as init } from './helpers.js';
import { inspectBrief, summarizeWork } from '../src/workflow.js';
import { actionableNotifications } from '../web/Notifications';

test('Work plans support review, comments, history and brief drift without a standalone plan',async t=>{
  const repo=await fs.mkdtemp(path.join(os.tmpdir(),'reduct-embedded-'));
  t.after(()=>fs.rm(repo,{recursive:true,force:true}));
  const store=await init(repo);
  const feature=await store.create('feature','Language','MODULE-gamma');
  let work=await store.create('work','Remove Follow Device',feature.meta.id);
  work=await store.saveBody(work.meta.id,'# Language\n\n## Plan\n\n### Proposed behavior\nUse English by default.\n\n### Open questions\nKeep saved choices?\n\n## Implementation outcome\nNot started.\n',work.hash);
  work=await store.submitReview(work.meta.id,work.hash);
  let docs=(await store.load()).docs;
  assert.equal(summarizeWork(work,docs).stage,'ready_for_review');
  assert.equal(summarizeWork(work,docs).questions[0].text,'Keep saved choices?');
  assert.ok(summarizeWork(work,docs).plan.includes('Use English'));
  assert.equal(actionableNotifications(docs,{},{}).filter(n=>n.kind==='review').length,1);
  const owner={name:'Owner',email:'owner@example.test'};
  const thread=await store.comment(work.meta.id,work.hash,'Keep my selection.','Use English by default.',owner);
  assert.equal(thread.meta.target_id,work.meta.id);
  const revision=docs.find(d=>d.meta.type==='snapshot'&&d.meta.parent===work.meta.id)!;
  assert.equal((await store.compare(work.meta.id,revision.meta.id)).added,0);
  let brief=await store.create('implementation','Language instructions',work.meta.id);
  assert.equal(brief.meta.source_plan,work.meta.id);
  brief=await store.saveBody(brief.meta.id,'# Instructions\n\nUse English and preserve saved choices.\n',brief.hash);
  brief=await store.readyBrief(brief.meta.id,brief.hash,owner);
  work=await store.saveBody(work.meta.id,work.body.replace('Not started.','Delivered.'),work.hash);
  assert.equal(work.meta.status,'ready_for_review');
  assert.equal(inspectBrief(brief,(await store.load()).docs).drift,'current');
  work=await store.saveBody(work.meta.id,work.body.replace('Use English by default.','Use Turkish by default.'),work.hash);
  assert.equal(work.meta.status,'draft');
  assert.equal(inspectBrief(brief,(await store.load()).docs).drift,'changed');
  assert.equal((await store.load()).errors.length,0);
  brief=await store.refreshBriefSource(brief.meta.id,brief.hash,work.hash);
  assert.equal(inspectBrief(brief,(await store.load()).docs).drift,'current');
  assert.equal(brief.meta.status,'draft');
});

test('a manually handed-off brief does not require a recorded approval',async t=>{
  const repo=await fs.mkdtemp(path.join(os.tmpdir(),'reduct-manual-'));
  t.after(()=>fs.rm(repo,{recursive:true,force:true}));
  const store=await init(repo);
  let work=await store.create('work','Pressure range','MODULE-gamma');
  work=await store.saveBody(work.meta.id,'# Pressure\n\n## Plan\nUse 10% to 150%.\n',work.hash);
  let brief=await store.create('implementation','Pressure instructions',work.meta.id);
  brief=await store.saveBody(brief.meta.id,'# Instructions\n\nUse 10% to 150% and persist the value.\n',brief.hash);
  assert.equal(brief.meta.approved_by,undefined);
  assert.ok((await store.briefing(brief.meta.id)).text.includes('No separate approval record is required'));
  assert.ok((await store.shortBriefing(brief.meta.id)).text.includes('No separate approval record is required'));
  const version=await store.snapshot(brief.meta.id,brief.hash,'manual handoff');
  work=await store.recordHandoff(work.meta.id,work.hash,version.meta.id,{name:'Owner',email:'owner@example.test'},'Implement this brief.');
  assert.equal(work.meta.handoff_revision_id,version.meta.id);
});

test('new briefs include exact reporting destinations for every affected feature',async t=>{
  const repo=await fs.mkdtemp(path.join(os.tmpdir(),'reduct-destinations-'));
  t.after(()=>fs.rm(repo,{recursive:true,force:true}));
  const store=await init(repo);
  const a=await store.create('feature','Language','MODULE-gamma');
  const b=await store.create('feature','Reader','MODULE-beta');
  let work=await store.create('work','Language change',a.meta.id);
  work=await store.updateWork(work.meta.id,work.hash,{workflow_mode:'simple',status:'ready_for_review',affected_features:[a.meta.id,b.meta.id]});
  const brief=await store.create('implementation','Language instructions',work.meta.id);
  assert.ok(brief.body.includes(`Work: ${path.join(store.root,work.path)} (${work.meta.id})`));
  for(const feature of [a,b])assert.ok(brief.body.includes(`Feature: ${path.join(store.root,feature.path)} (${feature.meta.id})`));
  const filled=await store.saveBody(brief.meta.id,brief.body.replaceAll(/\[Write[^\]]*\]/g,'Settled instructions.'),brief.hash);
  const docs=(await store.load()).docs;
  assert.equal(summarizeWork(work,docs).stage,'ready_for_implementation');
  assert.equal(actionableNotifications(docs,{[filled.meta.id]:inspectBrief(filled,docs)},{}).some(n=>n.kind==='review'&&n.targetId===work.meta.id),false);
  assert.equal(filled.meta.approved_by,undefined);
  const incomplete=await store.saveBody(filled.meta.id,brief.body,filled.hash);
  assert.equal(summarizeWork(work,(await store.load()).docs).stage,'ready_for_review');
  assert.equal(actionableNotifications((await store.load()).docs,{[incomplete.meta.id]:inspectBrief(incomplete,(await store.load()).docs)},{}).some(n=>n.kind==='review'&&n.targetId===work.meta.id),true);
});
